-- ============================================================================
-- Mizys CRM — MÓDULO 5 (insumos) e MARGEM ALVO
--
-- Rode uma vez no SQL Editor do Supabase. É idempotente: rodar duas vezes não
-- quebra nada e não duplica os materiais de exemplo.
--
-- O que entra:
--   1. `materiais`  — o catálogo de uniforme, EPI, material de limpeza e exames
--   2. `propostas.materiais`    — os insumos escolhidos em cada proposta
--   3. `propostas.margem_alvo`  — a margem líquida desejada, em %
--
-- Por que insumo não é equipamento: equipamento é bem durável e o valor cheio
-- cai todo mês. Insumo é reposição — o que importa é o PRAZO DE TROCA. Um
-- conjunto de uniforme de R$ 190 trocado a cada 6 meses custa R$ 31,67 por
-- funcionário por mês, e é isso que tem que entrar no custo direto, não R$ 190.
-- ============================================================================

create table if not exists materiais (
  id bigint generated by default as identity primary key,
  nome text not null,
  -- Só rótulo, para agrupar na tela. Não muda conta nenhuma.
  categoria text not null default 'Material',
  unidade text not null default 'un',
  -- Valor de AQUISIÇÃO de uma unidade, não o custo mensal.
  valor numeric(12,2) not null default 0,
  -- De quantos em quantos meses se repõe. 1 = todo mês; 6 = duas vezes ao ano.
  -- O custo mensal é valor ÷ meses.
  meses integer not null default 1 check (meses >= 1),
  -- Por quanto multiplicar. Errar aqui é o jeito mais rápido de orçar uniforme
  -- para 3 pessoas num contrato que tem 14: o fator de cobertura faz o
  -- headcount ser bem maior que o número de postos.
  --   funcionario · uniforme, EPI, exame       → × nº de funcionários
  --   posto       · rádio, chave, livro        → × nº de postos
  --   contrato    · produto da área comum      → × 1
  base text not null default 'funcionario'
    check (base in ('funcionario','posto','contrato')),
  obs text,
  ativo boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists materiais_nome_idx on materiais (lower(nome));

-- `materiais` na proposta: [{ "id": 3, "qtd": 2 }]  — qtd é por BASE do
-- material (2 conjuntos de uniforme POR FUNCIONÁRIO, não 2 no total).
alter table propostas add column if not exists materiais jsonb not null default '[]';

-- Margem líquida desejada, em %. Preenchida, ela manda no lucro de planilha:
-- o motor resolve L = (1−T) ÷ [((1−T) − m) × (1−d)] − 1. Zero = o vendedor
-- digita o lucro de planilha à mão, como antes.
alter table propostas add column if not exists margem_alvo numeric(8,4) not null default 0;

-- ── triggers ────────────────────────────────────────────────────────────────
do $$
begin
  if not exists (select 1 from pg_trigger where tgname = 'tg_touch_materiais') then
    create trigger tg_touch_materiais before update on materiais
      for each row execute function tg_touch();
  end if;
  if not exists (select 1 from pg_trigger where tgname = 'tg_audit_materiais') then
    create trigger tg_audit_materiais after insert or update or delete on materiais
      for each row execute function tg_auditoria();
  end if;
end $$;

-- ── RLS: catálogo — todo autenticado lê, só admin/gestor escreve ────────────
alter table materiais enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies
                 where tablename = 'materiais' and policyname = 'materiais_ler') then
    create policy "materiais_ler" on materiais for select to authenticated using (true);
    create policy "materiais_inserir" on materiais for insert to authenticated
      with check (app_pode_gerir());
    create policy "materiais_editar" on materiais for update to authenticated
      using (app_pode_gerir()) with check (app_pode_gerir());
    create policy "materiais_apagar" on materiais for delete to authenticated
      using (app_pode_gerir());
  end if;
end $$;

