-- ── margem: sem valor padrão ────────────────────────────────────────────────
-- A margem alvo nasce VAZIA em cada proposta, de propósito: campo
-- pré-preenchido com número plausível é aceito sem ser olhado, e margem é
-- decisão comercial de cada contrato, não configuração de sistema. Quem manda
-- na tela é `proposta_margem_minima`, que já existe e é só informativo.
--
-- Este delete existe para quem chegou a rodar a primeira versão deste arquivo,
-- que criava uma `proposta_margem_alvo` com 12,5 — ela não é mais lida por
-- ninguém, e config que não faz nada é pior do que config nenhuma.
delete from configuracoes where chave = 'proposta_margem_alvo';

update configuracoes
   set descricao = 'Lucro de planilha padrão (%) — markup sobre o custo, usado só quando não há margem alvo'
 where chave = 'proposta_markup';

-- ── conferência ─────────────────────────────────────────────────────────────
select 'materiais' as tabela, count(*) as linhas from materiais
union all
select 'propostas.materiais', count(*) from information_schema.columns
 where table_name = 'propostas' and column_name = 'materiais'
union all
select 'propostas.margem_alvo', count(*) from information_schema.columns
 where table_name = 'propostas' and column_name = 'margem_alvo';
